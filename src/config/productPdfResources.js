/**
 * Helper function to get PDF resources for a specific product
 * @param {string} productId - The product identifier (e.g., 'msc-nastran')
 * @returns {object} - Object containing PDF resource paths
 */
export function getProductResources(productId) {
  return productPdfResources[productId] || {}
}

/**
 * Helper function to check if a product has any PDF resources
 * @param {string} productId - The product identifier
 * @returns {boolean} - True if product has resources
 */
export function hasProductResources(productId) {
  const resources = productPdfResources[productId]
  return resources && Object.keys(resources).length > 0
}
